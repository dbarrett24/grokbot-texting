/** Split TOML text into [[array-table]] blocks: [{ name, text }]. Top-level keys and [tables] are ignored. */
/** @param {string} toml @returns {{ name: string, text: string }[]} */
export function arrayTables(toml) {
  /** @type {{ name: string, lines: string[] }[]} */
  const out = [];
  /** @type {{ name: string, lines: string[] } | null} */
  let cur = null;
  for (const line of toml.split(/\r?\n/)) {
    const m = line.match(/^\s*\[\[\s*([A-Za-z0-9_.]+)\s*\]\]/);
    if (m) { cur = { name: m[1], lines: [line] }; out.push(cur); continue; }
    if (/^\s*\[[^[]/.test(line)) { cur = null; continue; }
    if (cur) cur.lines.push(line);
  }
  return out.map(({ name, lines }) => {
    while (lines.length && /^\s*(#.*)?$/.test(lines[lines.length - 1])) lines.pop();
    return { name, text: lines.join("\n") };
  });
}

/** @param {string} toml @param {string} key */
export function topKey(toml, key) {
  const m = toml.match(new RegExp(`^${key}\\s*=\\s*"([^"]*)"`, "m"));
  return m ? m[1] : undefined;
}

/** @param {string} mainToml */
export function buildWalkConfig(mainToml) {
  const date = topKey(mainToml, "compatibility_date");
  if (!date) throw new Error("wrangler.toml has no compatibility_date");
  const blocks = arrayTables(mainToml).filter((b) => COPIED_TABLES.includes(b.name));
  if (!blocks.some((b) => b.name === "rules")) throw new Error("wrangler.toml has no [[rules]]; harbor assets would not build");
  const vars = Object.entries(WALK_VARS).map(([k, v]) => `${k} = ${JSON.stringify(v)}`).join("\n");
  return [
    "# GENERATED by scripts/walk-config.mjs from wrangler.toml. Do not edit; do not deploy. Local walk only, fake values.",
    `name = "sms-relay-walk"`,
    `main = "tools/walk/entry.ts"`,
    `compatibility_date = "${date}"`,
    "",
    ...blocks.map((b) => b.text + "\n"),
    "[vars]",
    vars,
    "",
  ].join("\n");
}

export function writeWalkConfig(root = ROOT) {
  const text = buildWalkConfig(readFileSync(join(root, "wrangler.toml"), "utf8"));
  const path = join(root, WALK_CONFIG);
  writeFileSync(path, text);
  return path;
}

