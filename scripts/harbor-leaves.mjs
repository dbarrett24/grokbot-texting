#!/usr/bin/env node
// @ts-check
// Numbers are comma-separated so no run of digits looks like a phone number to test/phone-scan.ts.
// Generates src/harbor-leaves.ts: three original inline-SVG foliage layers (corners, vines, scatter) for the Harbor
// backdrop. Inline SVG needs no fetch, so it works under every page's CSP (even default-src 'none'). Deterministic.
import { writeFileSync } from "node:fs";

let seed = 7;
const rnd = () => ((seed = (seed * 16807) % 2147483647) / 2147483647);
const r1 = (/** @type {number} */ n) => Math.round(n * 10) / 10;
const INKS = ["#a3b04e", "#8ec5e8", "#b4c15a", "#5b9bd8"];
/** One leaf: blade + midrib, base at 0,0 pointing along +x, then placed. */
function leaf(/** @type {number} */ x, /** @type {number} */ y, /** @type {number} */ deg, /** @type {number} */ s, /** @type {number} */ op) {
  const ink = INKS[Math.floor(rnd() * INKS.length)];
  return `<g transform="translate(${r1(x)},${r1(y)}) rotate(${Math.round(deg)}) scale(${s.toFixed(2)})" opacity="${Math.max(0.04, op).toFixed(2)}"><use href="#hl" fill="${ink}"/></g>`;
}
const DEFS = `<defs><g id="hl"><path d="M0,0C14,-13,40,-15,62,0C40,15,14,13,0,0Z"/><path d="M2,0H58" stroke="#0b1626" stroke-opacity=".35" stroke-width="1.2"/></g></defs>`;
/** Nested svg pinned to a viewport corner; flip mirrors the drawing into that corner. */
const corner = (/** @type {string} */ x, /** @type {string} */ y, /** @type {string} */ flip, /** @type {string} */ body) => `<svg x="${x}" y="${y}" overflow="visible"><g transform="scale(${flip.replace(" ", ",")})">${body}</g></svg>`;
const wrap = (/** @type {string} */ body, defs = "") => `<svg class=hl-leaves aria-hidden=true focusable=false width="100%" height="100%">${DEFS.replace("</defs>", defs + "</defs>")}${body}</svg>`;

function cornerCluster() {
  let g = "";
  for (let i = 0; i < 16; i++) { const a = rnd() * 90, d = 20 + rnd() * 230, s = 1.9 - d / 200; g += leaf(Math.cos((a * Math.PI) / 180) * d, Math.sin((a * Math.PI) / 180) * d, a - 30 + rnd() * 60, Math.max(0.6, s), 0.27 - d / 1300); }
  return g;
}
function vine() {
  let p = "M0,-20", g = "";
  for (let y = 0; y <= 1600; y += 80) { const x = 26 + Math.sin(y / 120) * 18; p += `Q${r1(x + 22)},${y - 40},${r1(x)},${y}`; const side = (y / 80) % 2 ? 1 : -1; g += leaf(x, y, side > 0 ? 20 + rnd() * 30 : 160 - rnd() * 30, 0.8 + rnd() * 0.5, 0.2 + rnd() * 0.08); }
  return `<path d="${p}" fill="none" stroke="#a3b04e" stroke-opacity=".22" stroke-width="2"/>${g}`;
}
function scatter() {
  let g = "";
  const spots = [[4, 8], [12, 22], [3, 40], [9, 63], [5, 86], [18, 94], [30, 4], [70, 3], [88, 12], [96, 30], [92, 52], [97, 72], [86, 90], [62, 96], [40, 97], [22, 70], [78, 78], [80, 26]];
  for (const [x, y] of spots) { const edge = Math.min(x, 100 - x, y, 100 - y); g += `<svg x="${x}%" y="${y}%" overflow="visible">${leaf(0, 0, rnd() * 360, 0.7 + rnd() * 0.6, 0.3 - edge / 90)}</svg>`; }
  return g;
}
const C = cornerCluster(), C2 = cornerCluster();
const LEAVES = {
  corners: wrap(corner("0", "0", "1 1", '<use href="#hc1"/>') + corner("100%", "0", "-1 1", '<use href="#hc2"/>') + corner("0", "100%", "1 -1", '<use href="#hc2"/>') + corner("100%", "100%", "-1 -1", '<use href="#hc1"/>'), `<g id="hc1">${C}</g><g id="hc2">${C2}</g>`),
  vines: wrap(corner("0", "0", "1 1", '<use href="#hv"/>') + corner("100%", "0", "-1 1", '<use href="#hv"/>'), `<g id="hv">${vine()}</g>`),
  scatter: wrap(scatter()),
};
const out = `// GENERATED by scripts/harbor-leaves.mjs: do not edit. Original artwork (this repo's licence), no external source.\n` +
  `export const HARBOR_LEAVES = ${JSON.stringify(LEAVES, null, 1)} as const;\nexport type LeavesOption = keyof typeof HARBOR_LEAVES;\n`;
writeFileSync(new URL("../src/harbor-leaves.ts", import.meta.url), out);
for (const [k, v] of Object.entries(LEAVES)) console.log(k, new TextEncoder().encode(v).length, "bytes");
